from __future__ import annotations

from datetime import datetime

from models.schemas import AnalysisResult


def build_report_text(result: AnalysisResult, target_field: str, custom_field: str | None) -> str:
    field_label = custom_field if target_field == "Other" and custom_field else target_field
    lines: list[str] = []
    a = lines.append

    a("=" * 60)
    a("  RESUMEAI - RESUME ANALYSIS REPORT")
    a("=" * 60)
    a(f"Generated: {datetime.now().strftime('%Y-%m-%d %H:%M')}")
    a(f"Target field: {field_label}")
    if result.is_mock:
        a("Mode: DEMO / MOCK ANALYSIS (no live AI call was made)")
    a("")

    a("-" * 60)
    a("SCORES")
    a("-" * 60)
    a(f"ATS Score:        {result.ats_score}/100")
    a(f"Job Match:        {result.job_match_score}%")
    a(f"Keyword Match:    {result.keyword_match_score}%")
    a(f"Skills Match:     {result.skills_match_score}%")
    a("(ATS score is an estimate, not a guarantee of a real employer's ATS.)")
    a("")

    a("-" * 60)
    a("ATS COMPATIBILITY BREAKDOWN")
    a("-" * 60)
    f = result.ats_feedback
    a(f"Formatting:   {f.formatting}%")
    a(f"Keywords:     {f.keywords}%")
    a(f"Structure:    {f.structure}%")
    a(f"Readability:  {f.readability}%")
    a(f"Skills:       {f.skills}%")
    a("")
    a(f.explanation)
    a("")

    a("-" * 60)
    a("KEYWORD ANALYSIS")
    a("-" * 60)
    a("Matched:   " + (", ".join(result.matched_keywords) or "None found"))
    a("Missing:   " + (", ".join(result.missing_keywords) or "None"))
    a("Partial:   " + (", ".join(result.partial_keywords) or "None"))
    a("")

    a("-" * 60)
    a("SKILL GAP ANALYSIS")
    a("-" * 60)
    a("Current skills:  " + (", ".join(result.current_skills) or "None detected"))
    a("Required skills: " + (", ".join(result.required_skills) or "None detected"))
    for g in result.skill_gaps:
        a(f"  - {g.skill} ({g.priority.value if hasattr(g.priority, 'value') else g.priority})")
    a("")

    a("-" * 60)
    a("RESUME IMPROVEMENTS")
    a("-" * 60)
    a("Current summary:")
    a(f"  {result.summary_current or '(not found)'}")
    a("Suggested summary:")
    a(f"  {result.summary_improvement or '(not enough resume text to suggest one)'}")
    a("")
    for p in result.project_improvements:
        a(f"Project - {p.title}")
        a(f"  Current:   {p.before}")
        a(f"  Suggested: {p.after}")
        a("")
    for i, e in enumerate(result.experience_improvements, 1):
        a(f"Bullet {i}")
        a(f"  Before: {e.before}")
        a(f"  After:  {e.after}")
        a("")

    a("-" * 60)
    a(f"CAREER IMPROVEMENT - {field_label}")
    a("-" * 60)
    a(f"Readiness score: {result.field_readiness_score}%")
    a("Recommended improvements:")
    for i, r in enumerate(result.career_recommendations, 1):
        a(f"  {i}. {r}")
    a("Recommended skills to build: " + (", ".join(result.recommended_skills) or "None"))
    a("")

    a("-" * 60)
    a("INTERVIEW PREPARATION")
    a("-" * 60)
    for cat in ["Technical", "Project", "HR"]:
        cat_questions = [q for q in result.interview_questions if (q.category.value if hasattr(q.category, "value") else q.category) == cat]
        if not cat_questions:
            continue
        a(f"{cat} Questions:")
        for q in cat_questions:
            a(f"  Q: {q.question}")
            if q.what_is_tested:
                a(f"     (Tests: {q.what_is_tested})")
        a("")

    a("=" * 60)
    a("Generated by ResumeAI - an NTCC academic project.")
    a("=" * 60)

    return "\n".join(lines)
